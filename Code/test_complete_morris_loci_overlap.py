#!/usr/bin/env python3
"""Test the complete Morris et al. eBMD locus set against compartment differences.

The analysis uses all 1,103 conditionally independent signals at 515 loci from
the main GWAS plus the three sex-specific signals that add three loci (1,106
signals at 518 loci in total). Coordinates are lifted from hg19 to GRCh38.

Two region-level tests are prespecified: selected 160-kb bins that directly
contain a signal, and selected bins within 500 kb of any signal. Empirical null
distributions are generated by chromosome-wise circular shifts across the
12,608 analyzable bins, preserving the number and clustering of selected bins.
"""

from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from openpyxl import load_workbook


ROOT = Path(__file__).resolve().parents[1]
from pyliftover import LiftOver


SOURCE = ROOT / "Source_Data/S2_Table_primary_160kb_compartment_comparison.csv"
WORKBOOK = ROOT / "Reference_Data/Morris_2019_Supplementary_Tables_1-22.xlsx"
CHAIN = ROOT / "Reference_Data/hg19ToHg38.over.chain.gz"
OUT = ROOT / "Results"
N_PERM = 20_000
SEED = 20261105
BIN_SIZE = 160_000


def consensus(state: str, positive_fraction: str) -> bool:
    if state not in {"A", "B"} or positive_fraction == "":
        return False
    value = float(positive_fraction)
    return value >= 0.8 if state == "A" else value <= 0.2


def tested(row: dict[str, str]) -> bool:
    return (
        consensus(row["hMSC_state"], row["hMSC_positive_fraction"])
        and consensus(row["AC_state"], row["AC_positive_fraction"])
        and row["AC_vs_hMSC_delta_z"] != ""
    )


def sheet_rows(workbook, name: str) -> tuple[list[object], list[tuple[object, ...]]]:
    ws = workbook[name]
    header = list(next(ws.iter_rows(min_row=4, max_row=4, values_only=True)))
    rows = [
        row
        for row in ws.iter_rows(min_row=5, values_only=True)
        if isinstance(row[0], int)
    ]
    return header, rows


def read_signals() -> list[dict[str, object]]:
    workbook = load_workbook(WORKBOOK, read_only=True, data_only=True)
    h2, main = sheet_rows(workbook, "Supplementary Table 2")
    h6, sex = sheet_rows(workbook, "Supplementary Table 6")
    signals: list[dict[str, object]] = []
    main_rsids = set()
    for row in main:
        rsid = str(row[h2.index("RSID")])
        main_rsids.add(rsid)
        signals.append(
            {
                "locus_id": f'main_{int(row[h2.index("L.BIN")]):03d}',
                "source": "main_GWAS",
                "rsid": rsid,
                "nearest_gene_reported_by_Morris": str(row[h2.index("C.GENE")]),
                "chrom_hg19": str(row[h2.index("CHR")]),
                "position_hg19_1based": int(row[h2.index("BP")]),
            }
        )
    for row in sex:
        rsid = str(row[h6.index("RSID")])
        if rsid in main_rsids:
            continue
        signals.append(
            {
                "locus_id": f"sex_specific_{rsid}",
                "source": "sex_specific_additional_locus",
                "rsid": rsid,
                "nearest_gene_reported_by_Morris": str(row[h6.index("C.GENE")]),
                "chrom_hg19": str(row[h6.index("CHR")]),
                "position_hg19_1based": int(row[h6.index("BP")]),
            }
        )
    return signals


def bh_adjust(values: list[float]) -> list[float]:
    n = len(values)
    order = sorted(range(n), key=values.__getitem__)
    adjusted = [1.0] * n
    running = 1.0
    for rank_index in range(n - 1, -1, -1):
        idx = order[rank_index]
        rank = rank_index + 1
        running = min(running, values[idx] * n / rank)
        adjusted[idx] = min(1.0, running)
    return adjusted


def main() -> None:
    rows_by_chrom: dict[str, list[dict[str, str]]] = defaultdict(list)
    with SOURCE.open(newline="") as handle:
        for row in csv.DictReader(handle):
            if row["chrom"] in {f"chr{i}" for i in range(1, 23)} and tested(row):
                rows_by_chrom[row["chrom"]].append(row)
    for chrom in rows_by_chrom:
        rows_by_chrom[chrom].sort(key=lambda row: int(row["start"]))
    tested_bins = {
        (chrom, int(row["start"]))
        for chrom, rows in rows_by_chrom.items()
        for row in rows
    }
    selected_bins = {
        (chrom, int(row["start"]))
        for chrom, rows in rows_by_chrom.items()
        for row in rows
        if row["AC_vs_hMSC_consensus_effect_difference"].lower() == "true"
    }

    lifter = LiftOver(str(CHAIN))
    signals = read_signals()
    lifted = []
    for signal in signals:
        chrom = "chr" + str(signal["chrom_hg19"]).replace("23", "X")
        hits = lifter.convert_coordinate(chrom, int(signal["position_hg19_1based"]) - 1)
        row = dict(signal)
        if len(hits) == 1:
            chrom38, pos38, strand, _ = hits[0]
            row.update(
                {
                    "chrom_grch38": chrom38,
                    "position_grch38_1based": int(pos38) + 1,
                    "strand": strand,
                    "liftover_status": "unique",
                    "bin_start_grch38": (int(pos38) // BIN_SIZE) * BIN_SIZE,
                }
            )
        else:
            row.update(
                {
                    "chrom_grch38": "",
                    "position_grch38_1based": "",
                    "strand": "",
                    "liftover_status": "unmapped" if not hits else "multiple",
                    "bin_start_grch38": "",
                }
            )
        lifted.append(row)

    direct_bins: set[tuple[str, int]] = set()
    window_bins: set[tuple[str, int]] = set()
    direct_loci: set[str] = set()
    for signal in lifted:
        if signal["liftover_status"] != "unique":
            continue
        chrom = str(signal["chrom_grch38"])
        if chrom not in rows_by_chrom:
            continue
        pos0 = int(signal["position_grch38_1based"]) - 1
        direct = (chrom, (pos0 // BIN_SIZE) * BIN_SIZE)
        signal["direct_bin_is_tested"] = direct in tested_bins
        signal["direct_bin_is_selected_difference"] = direct in selected_bins
        if direct in tested_bins:
            direct_bins.add(direct)
            if direct in selected_bins:
                direct_loci.add(str(signal["locus_id"]))
        for row in rows_by_chrom[chrom]:
            start, end = int(row["start"]), int(row["end"])
            if start <= pos0 + 500_000 and end >= pos0 - 500_000:
                window_bins.add((chrom, start))

    with (OUT / "morris_518_loci_1106_signals_grch38.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(lifted[0]))
        writer.writeheader()
        writer.writerows(lifted)

    annotations = {
        "direct_signal_containing_160kb_bin": direct_bins,
        "within_500kb_of_conditionally_independent_signal": window_bins,
    }
    rng = np.random.default_rng(SEED)
    results = []
    for name, annotated_bins in annotations.items():
        observed = 0
        null = np.zeros(N_PERM, dtype=int)
        for chrom, rows in rows_by_chrom.items():
            selection = np.array(
                [
                    row["AC_vs_hMSC_consensus_effect_difference"].lower() == "true"
                    for row in rows
                ],
                dtype=int,
            )
            annotation = np.array(
                [(chrom, int(row["start"])) in annotated_bins for row in rows], dtype=int
            )
            observed += int(np.sum(selection * annotation))
            # counts[k] is overlap after a chromosome-specific circular shift.
            counts = np.rint(
                np.fft.ifft(np.fft.fft(selection) * np.conj(np.fft.fft(annotation))).real
            ).astype(int)
            null += counts[rng.integers(0, len(rows), size=N_PERM)]
        null_mean = float(null.mean())
        p = (1 + int(np.sum(null >= observed))) / (N_PERM + 1)
        results.append(
            {
                "annotation": name,
                "tested_bins": len(tested_bins),
                "selected_bins": len(selected_bins),
                "GWAS_annotated_tested_bins": len(annotated_bins),
                "observed_selected_GWAS_bins": observed,
                "null_mean": round(null_mean, 4),
                "null_2.5_percentile": float(np.quantile(null, 0.025)),
                "null_97.5_percentile": float(np.quantile(null, 0.975)),
                "fold_over_null": round(observed / null_mean, 4) if null_mean else "",
                "empirical_p": p,
                "permutations": N_PERM,
                "seed": SEED,
            }
        )
    for row, fdr in zip(results, bh_adjust([float(r["empirical_p"]) for r in results])):
        row["BH_FDR_across_2_tests"] = fdr
    with (OUT / "morris_locus_overlap_circular_shift.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(results[0]))
        writer.writeheader()
        writer.writerows(results)

    summary = [
        ("signals_total", len(lifted)),
        ("loci_total", len({str(row["locus_id"]) for row in lifted})),
        ("signals_uniquely_lifted", sum(row["liftover_status"] == "unique" for row in lifted)),
        ("tested_bins", len(tested_bins)),
        ("selected_bins", len(selected_bins)),
        ("unique_loci_with_signal_directly_in_selected_bin", len(direct_loci)),
    ]
    with (OUT / "morris_locus_overlap_summary.csv").open("w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["metric", "value"])
        writer.writerows(summary)
    print("\n".join(f"{key}: {value}" for key, value in summary))
    for row in results:
        print(
            row["annotation"], "observed", row["observed_selected_GWAS_bins"],
            "null", row["null_mean"], "fold", row["fold_over_null"],
            "p", f'{row["empirical_p"]:.4g}',
            "FDR", f'{row["BH_FDR_across_2_tests"]:.4g}',
        )


if __name__ == "__main__":
    main()
